"""
Pydantic model representing the detailed validation report generated by the pipeline.
"""

from pydantic import BaseModel, Field
from typing import Dict, List, Optional
from souscription.models.enums import ValidationStatus

class FieldValidation(BaseModel):
    field_name: str
    expected_value: str
    extracted_value: str
    status: ValidationStatus
    score: Optional[float] = None
    message: Optional[str] = None

class DocumentValidationReport(BaseModel):
    document_name: str
    document_type: str
    status: ValidationStatus
    message: Optional[str] = None
    local_checks: List[FieldValidation] = []

class CrossReferenceValidationReport(BaseModel):
    status: ValidationStatus
    checks: List[FieldValidation] = []

class FullValidationReport(BaseModel):
    overall_status: ValidationStatus
    document_reports: List[DocumentValidationReport] = []
    cross_reference_report: CrossReferenceValidationReport
    rejection_reasons: List[str] = []
